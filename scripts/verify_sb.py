"""
Functional check: RTL case table must match scripts.truth_table.s0
Run from repo root or this folder:
  python verify_sb.py
Requires: verilog model copied logic OR import truth_table from same dir.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from truth_table import s0, table_64

# Verilog case order: same as {x} 0..63
CASE_OUTPUTS = [
    0x00, 0x36, 0x30, 0x0D, 0x0F, 0x12, 0x35, 0x23, 0x19, 0x3F, 0x2D, 0x34, 0x03, 0x14, 0x29, 0x21,
    0x3B, 0x24, 0x02, 0x22, 0x0A, 0x08, 0x39, 0x25, 0x3C, 0x13, 0x2A, 0x0E, 0x32, 0x1A, 0x3A, 0x18,
    0x27, 0x1B, 0x15, 0x11, 0x10, 0x1D, 0x01, 0x3E, 0x2F, 0x28, 0x33, 0x38, 0x07, 0x2B, 0x2C, 0x26,
    0x1F, 0x0B, 0x04, 0x1C, 0x3D, 0x2E, 0x05, 0x31, 0x09, 0x06, 0x17, 0x20, 0x1E, 0x0C, 0x37, 0x16,
]


def main() -> int:
    gold = table_64()
    assert gold == CASE_OUTPUTS, "internal case list drift"
    for i in range(64):
        if s0(i) != gold[i]:
            print(f"mismatch at {i}: s0={s0(i):02x} gold={gold[i]:02x}")
            return 1
    print("OK: 64/64 entries match golden S0.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
