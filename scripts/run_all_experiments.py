"""
Run all currently available experiments and write a CSV summary.

This script is Windows-friendly and degrades gracefully:
- Always runs Python-based checks.
- Runs simulation/synthesis only if required executables exist.
- Runs NanGate mapping/STA only if yosys/opensta and liberty file are available.
"""
from __future__ import annotations

import csv
import os
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / "scripts"
SYNTH = ROOT / "synth"
RESULTS = ROOT / "results"
BUILD = ROOT / "build"


@dataclass
class StepResult:
    name: str
    status: str
    returncode: int
    note: str


def run_cmd(name: str, cmd: list[str], cwd: Optional[Path] = None) -> StepResult:
    try:
        proc = subprocess.run(
            cmd,
            cwd=str(cwd or ROOT),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
        note = (proc.stdout + "\n" + proc.stderr).strip()
        return StepResult(name=name, status="ok" if proc.returncode == 0 else "fail", returncode=proc.returncode, note=note)
    except FileNotFoundError as exc:
        return StepResult(name=name, status="skip", returncode=127, note=f"missing executable: {exc}")


def which(name: str) -> Optional[str]:
    return shutil.which(name)


def find_sta() -> Optional[str]:
    """OpenSTA binary may be named `sta` or `opensta`; oss-cad-suite Windows often has sta.exe next to yosys."""
    for name in ("opensta", "sta"):
        p = which(name)
        if p:
            return p
    yosys_bin = which("yosys")
    if yosys_bin:
        bindir = Path(yosys_bin).resolve().parent
        for exe in ("sta.exe", "sta", "opensta.exe", "opensta"):
            cand = bindir / exe
            if cand.is_file():
                return str(cand)
    suite = os.getenv("OSS_CAD_SUITE")
    if suite:
        for exe in ("sta.exe", "sta"):
            cand = Path(suite) / "bin" / exe
            if cand.is_file():
                return str(cand)
    return None


def find_liberty() -> Optional[Path]:
    env = os.getenv("NANGATE_LIB")
    if env:
        p = Path(env)
        if p.exists():
            return p
    candidate = ROOT / "lib" / "NangateOpenCellLibrary_typical.lib"
    if candidate.exists():
        return candidate
    return None


def format_liberty_token(liberty: Path) -> str:
    """Path token for Yosys/OpenSTA: forward slashes; quote if spaces."""
    s = str(liberty.resolve()).replace("\\", "/")
    if any(c in s for c in (" ", ";", "(", ")")):
        return '"' + s.replace('"', '\\"') + '"'
    return s


def write_yosys_map_script(liberty: Path, dest: Path) -> None:
    """
    Yosys .ys scripts do NOT Tcl-expand $::env(...); embed absolute liberty path.

    Env: CHALLENGE_RTL — space-separated Verilog files (default rtl/sb_lut_baseline.v)
          CHALLENGE_TOP — top module name (default SB)
    """
    lib = format_liberty_token(liberty)
    rtl_files = [p.strip() for p in os.getenv("CHALLENGE_RTL", "rtl/sb_lut_baseline.v").split() if p.strip()]
    top = os.getenv("CHALLENGE_TOP", "SB").strip()
    read_lines = [f"read_verilog -sv {fn}" for fn in rtl_files]
    dest.write_text(
        "\n".join(
            [
                "# AUTO-GENERATED by scripts/run_all_experiments.py — do not edit.",
                "# Env overrides: CHALLENGE_RTL, CHALLENGE_TOP",
                # NanGate/open libs often include clock-gating cells without output `function:` (e.g. CLKGATETST_X1 IQ).
                f"read_liberty -ignore_miss_func {lib}",
                *read_lines,
                f"hierarchy -check -top {top}",
                "",
                f"synth -top {top} -flatten",
                "opt",
                f"dfflibmap -liberty {lib}",
                f"abc -liberty {lib}",
                "opt_clean",
                "",
                f"stat -liberty {lib}",
                "write_verilog -noattr -noparallelcase build/sb_mapped_nangate.v",
                "",
            ]
        ),
        encoding="utf-8",
        newline="\n",
    )


def write_sta_run_script(liberty: Path, dest: Path) -> None:
    lib = format_liberty_token(liberty)
    top = os.getenv("CHALLENGE_TOP", "SB").strip()
    dest.write_text(
        "\n".join(
            [
                "# AUTO-GENERATED by scripts/run_all_experiments.py — do not edit.",
                f"# CHALLENGE_TOP={top}",
                f"read_liberty {lib}",
                "read_verilog build/sb_mapped_nangate.v",
                f"link_design {top}",
                "",
                "# Pure combinational block: without a clock, OpenSTA reports \"No paths found\".",
                "create_clock -name __sb_virtual -period 1000",
                "set_input_delay 0 -clock __sb_virtual [all_inputs]",
                "set_output_delay 0 -clock __sb_virtual [all_outputs]",
                "",
                "report_checks -path_delay max -digits 6",
                "report_tns",
                "report_wns",
                "",
                "# Without this, OpenSTA waits on stdin (interactive) and automation hangs.",
                "exit 0",
                "",
            ]
        ),
        encoding="utf-8",
        newline="\n",
    )


NOTE_MAX_LEN = 12000


def truncate_note(note: str) -> str:
    if len(note) <= NOTE_MAX_LEN:
        return note
    return note[: NOTE_MAX_LEN - 80] + "\n... [truncated; set EXPERIMENT_FULL_LOG=1 to disable]"


def write_csv(rows: list[StepResult]) -> Path:
    RESULTS.mkdir(parents=True, exist_ok=True)
    out = RESULTS / "experiment_summary.csv"
    full = os.getenv("EXPERIMENT_FULL_LOG", "").strip().lower() in ("1", "true", "yes")
    with out.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["step", "status", "return_code", "note"])
        for r in rows:
            n = r.note.replace("\r\n", "\n")
            if not full:
                n = truncate_note(n)
            w.writerow([r.name, r.status, r.returncode, n])
    return out


def main() -> int:
    BUILD.mkdir(parents=True, exist_ok=True)
    rows: list[StepResult] = []

    py = sys.executable
    rows.append(run_cmd("verify_truth_table", [py, str(SCRIPTS / "verify_sb.py")], cwd=ROOT))
    rows.append(run_cmd("check_sbox_properties", [py, str(SCRIPTS / "check_sbox_properties.py")], cwd=ROOT))
    rows.append(run_cmd("regen_lut_verilog", [py, str(SCRIPTS / "gen_lut_verilog.py")], cwd=ROOT))
    rows.append(run_cmd("verify_after_regen", [py, str(SCRIPTS / "verify_sb.py")], cwd=ROOT))

    iverilog = which("iverilog")
    vvp = which("vvp")
    if iverilog and vvp:
        rows.append(
            run_cmd(
                "iverilog_sim",
                [iverilog, "-g2012", "-o", str(BUILD / "tb_sb.vvp"), str(ROOT / "rtl" / "sb_lut_baseline.v"), str(ROOT / "sim" / "tb_sb.v")],
                cwd=ROOT,
            )
        )
        rows.append(run_cmd("vvp_run", [vvp, str(BUILD / "tb_sb.vvp")], cwd=ROOT))
    else:
        rows.append(
            StepResult(
                name="iverilog_sim",
                status="skip",
                returncode=127,
                note="iverilog/vvp not found on PATH",
            )
        )

    yosys = which("yosys")
    sta_exe = find_sta()
    liberty = find_liberty()
    map_run = BUILD / "yosys_map_nangate_run.ys"
    sta_run = BUILD / "sta_sb_run.tcl"

    if yosys:
        rows.append(run_cmd("yosys_generic_synth", [yosys, "-s", str(SYNTH / "yosys_sb.ys")], cwd=ROOT))
    else:
        rows.append(StepResult(name="yosys_generic_synth", status="skip", returncode=127, note="yosys not found on PATH"))

    if not yosys or not liberty:
        missing = []
        if not yosys:
            missing.append("yosys")
        if not liberty:
            missing.append("NangateOpenCellLibrary_typical.lib (or env NANGATE_LIB)")
        note = f"missing: {', '.join(missing)}"
        rows.append(StepResult(name="nangate_map", status="skip", returncode=127, note=note))
        rows.append(StepResult(name="nangate_sta", status="skip", returncode=127, note=note))
    else:
        write_yosys_map_script(liberty, map_run)
        write_sta_run_script(liberty, sta_run)
        proc_map = subprocess.run(
            [yosys, "-s", str(map_run)],
            cwd=str(ROOT),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
        rows.append(
            StepResult(
                name="nangate_map",
                status="ok" if proc_map.returncode == 0 else "fail",
                returncode=proc_map.returncode,
                note=(proc_map.stdout + "\n" + proc_map.stderr).strip(),
            )
        )
        if proc_map.returncode != 0:
            rows.append(
                StepResult(
                    name="nangate_sta",
                    status="skip",
                    returncode=0,
                    note="skipped because nangate_map failed",
                )
            )
        elif not sta_exe:
            rows.append(
                StepResult(
                    name="nangate_sta",
                    status="skip",
                    returncode=127,
                    note=(
                        "sta/opensta not found on PATH; oss-cad-suite: run start.bat first, "
                        "or add ...\\oss-cad-suite\\bin to PATH, or set OSS_CAD_SUITE"
                    ),
                )
            )
        else:
            # Prefer `sta -exit` (batch); TCL also ends with `exit 0` so older sta without `-exit` still exits.
            sta_timeout = os.getenv("EXPERIMENT_STA_TIMEOUT_SEC", "600").strip()
            try:
                to = int(sta_timeout)
            except ValueError:
                to = 600
            timeout_kw = {"timeout": to} if to > 0 else {}

            def _run_sta(cmd: list[str]) -> subprocess.CompletedProcess[str]:
                return subprocess.run(
                    cmd,
                    cwd=str(ROOT),
                    capture_output=True,
                    text=True,
                    encoding="utf-8",
                    errors="replace",
                    **timeout_kw,
                )

            try:
                proc_sta = _run_sta([sta_exe, "-exit", str(sta_run)])
                comb = ((proc_sta.stderr or "") + (proc_sta.stdout or "")).lower()
                if proc_sta.returncode != 0 and any(
                    s in comb for s in ("unknown option", "invalid option", "bad option", "illegal option")
                ):
                    proc_sta = _run_sta([sta_exe, str(sta_run)])
                rows.append(
                    StepResult(
                        name="nangate_sta",
                        status="ok" if proc_sta.returncode == 0 else "fail",
                        returncode=proc_sta.returncode,
                        note=(proc_sta.stdout + "\n" + proc_sta.stderr).strip(),
                    )
                )
            except subprocess.TimeoutExpired as exc:
                rows.append(
                    StepResult(
                        name="nangate_sta",
                        status="fail",
                        returncode=124,
                        note=(
                            f"timeout after {to}s (set EXPERIMENT_STA_TIMEOUT_SEC or 0 to disable); "
                            f"partial out: {(exc.stdout or '')[:4000]}"
                        ),
                    )
                )

    out = write_csv(rows)
    print(f"Wrote summary: {out}")
    for r in rows:
        print(f"[{r.status}] {r.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
